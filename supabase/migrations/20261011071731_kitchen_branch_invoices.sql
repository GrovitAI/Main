-- Task 188: saved branch invoices. No sale, stock or balance is posted by creation.
CREATE TABLE IF NOT EXISTS public.kitchen_invoices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  tenant_id uuid NOT NULL,
  branch_id uuid NOT NULL REFERENCES public.branches(id),
  party_id uuid NOT NULL REFERENCES public.kitchen_parties(id),
  kitchen_name text NOT NULL,
  party_name text NOT NULL,
  start_date date NOT NULL,
  end_date date NOT NULL CHECK (end_date >= start_date),
  total_paise bigint NOT NULL CHECK (total_paise >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid NOT NULL,
  created_by_name text NOT NULL,
  cancelled_at timestamptz,
  cancel_reason text CHECK (length(cancel_reason) BETWEEN 1 AND 200)
);
CREATE INDEX IF NOT EXISTS kitchen_invoices_scope_idx ON public.kitchen_invoices(tenant_id, branch_id, created_at DESC, id);
CREATE INDEX IF NOT EXISTS kitchen_invoices_branch_idx ON public.kitchen_invoices(branch_id);
CREATE INDEX IF NOT EXISTS kitchen_invoices_party_idx ON public.kitchen_invoices(party_id);
CREATE TABLE IF NOT EXISTS public.kitchen_invoice_deliveries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL,
  branch_id uuid NOT NULL REFERENCES public.branches(id),
  invoice_id uuid NOT NULL REFERENCES public.kitchen_invoices(id),
  entry_id uuid NOT NULL REFERENCES public.kitchen_entries(id),
  entry_date date NOT NULL,
  amount_paise bigint NOT NULL CHECK (amount_paise >= 0),
  lines jsonb NOT NULL CHECK (jsonb_typeof(lines) = 'array'),
  is_active boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS kitchen_invoice_delivery_once ON public.kitchen_invoice_deliveries(entry_id) WHERE is_active;
CREATE INDEX IF NOT EXISTS kitchen_invoice_deliveries_scope_idx ON public.kitchen_invoice_deliveries(tenant_id, branch_id, invoice_id);
CREATE INDEX IF NOT EXISTS kitchen_invoice_deliveries_invoice_idx ON public.kitchen_invoice_deliveries(invoice_id);
CREATE INDEX IF NOT EXISTS kitchen_invoice_deliveries_branch_idx ON public.kitchen_invoice_deliveries(branch_id);
CREATE INDEX IF NOT EXISTS kitchen_invoice_deliveries_entry_idx ON public.kitchen_invoice_deliveries(entry_id);
-- Retry keys prevent a lost response from recording a partial payment twice.
CREATE TABLE IF NOT EXISTS public.kitchen_invoice_payments (
  tenant_id uuid NOT NULL,
  branch_id uuid NOT NULL REFERENCES public.branches(id),
  invoice_id uuid NOT NULL REFERENCES public.kitchen_invoices(id),
  request_key text NOT NULL CHECK (length(request_key) BETWEEN 12 AND 80),
  payment_id uuid NOT NULL REFERENCES public.kitchen_entries(id),
  PRIMARY KEY (invoice_id, request_key)
);
CREATE INDEX IF NOT EXISTS kitchen_invoice_payments_branch_idx ON public.kitchen_invoice_payments(branch_id);
CREATE INDEX IF NOT EXISTS kitchen_invoice_payments_payment_idx ON public.kitchen_invoice_payments(payment_id);
